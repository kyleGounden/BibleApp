type Extra = Partial<Omit<Kin, 'id' | 'name'>>

function k(id: string, name: string, refs: string | string[], extra?: Extra): Kin {
  return { id, name, refs: typeof refs === 'string' ? [refs] : refs, ...extra }
}

function sons(father: string, ref: string, tribe: string | undefined, rows: Array<[string, string, Extra?]>): Kin[] {
  return rows.map(([id, name, extra]) => k(id, name, ref, { father, tribe, ...extra }))
}

